-- V10: patient portal - bookings from the portal, visit ratings, support tickets.

-- A booking made in the portal is a care request with a preferred date and time slot.
ALTER TABLE care_requests
    ADD COLUMN preferred_date               DATE,
    ADD COLUMN time_slot                    VARCHAR(12),     -- MORNING | AFTERNOON | EVENING
    ADD COLUMN care_recipient_name          VARCHAR(150),    -- booking for someone else
    ADD COLUMN care_recipient_phone         VARCHAR(30),
    ADD COLUMN care_recipient_relationship  VARCHAR(60),
    ADD COLUMN cancel_reason                TEXT,
    ADD COLUMN cancelled_at                 TIMESTAMPTZ;

-- The patient's rating of a completed visit.
ALTER TABLE visits
    ADD COLUMN rating            SMALLINT CHECK (rating BETWEEN 1 AND 5),
    ADD COLUMN feedback_comment  TEXT,
    ADD COLUMN rated_at          TIMESTAMPTZ;

-- Patient <-> Customer Care conversations.
CREATE TABLE support_tickets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category            VARCHAR(20)   NOT NULL,
    subject             VARCHAR(150)  NOT NULL,
    status              VARCHAR(20)   NOT NULL DEFAULT 'OPEN',   -- OPEN | IN_PROGRESS | ESCALATED | RESOLVED | CLOSED
    priority            VARCHAR(10)   NOT NULL DEFAULT 'NORMAL', -- NORMAL | URGENT
    assigned_agent_id   BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    unread_for_patient  BOOLEAN       NOT NULL DEFAULT FALSE,    -- an agent replied
    unread_for_agent    BOOLEAN       NOT NULL DEFAULT TRUE,     -- the patient wrote
    last_message_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resolved_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_ticket_status   CHECK (status IN ('OPEN', 'IN_PROGRESS', 'ESCALATED', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_ticket_priority CHECK (priority IN ('NORMAL', 'URGENT'))
);
CREATE INDEX ix_tickets_patient ON support_tickets (patient_id, last_message_at DESC);
CREATE INDEX ix_tickets_status  ON support_tickets (status, last_message_at DESC);

CREATE TABLE ticket_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id    BIGINT        NOT NULL REFERENCES support_tickets (id) ON DELETE CASCADE,
    sender_id    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    sender_type  VARCHAR(10)   NOT NULL,       -- PATIENT | AGENT
    sender_name  VARCHAR(150),
    body         TEXT          NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_ticket_messages ON ticket_messages (ticket_id, created_at);

ALTER TABLE support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE ticket_messages ENABLE ROW LEVEL SECURITY;
