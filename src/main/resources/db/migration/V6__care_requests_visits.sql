-- V6: assigning care requests and the visit schedule.

-- The Admin page uses PENDING for new requests.
UPDATE care_requests SET status = 'PENDING' WHERE status = 'NEW';
ALTER TABLE care_requests ALTER COLUMN status SET DEFAULT 'PENDING';

ALTER TABLE care_requests
    ADD COLUMN assigned_provider_id  BIGINT REFERENCES providers (id) ON DELETE SET NULL,
    ADD COLUMN assigned_at           TIMESTAMPTZ,
    ADD COLUMN assigned_by_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN admin_note            TEXT,
    ADD COLUMN closure_note          TEXT,          -- provider's closing report
    ADD COLUMN closure_requested_at  TIMESTAMPTZ,
    ADD COLUMN closed_at             TIMESTAMPTZ,
    ADD COLUMN closed_by_id          BIGINT REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN closure_review_note   TEXT;          -- admin's note on approve / reason on send-back

-- Life of a request: PENDING -> ASSIGNED -> PENDING_CLOSURE -> COMPLETED (or CANCELLED)
ALTER TABLE care_requests ADD CONSTRAINT ck_care_requests_status
    CHECK (status IN ('PENDING', 'ASSIGNED', 'PENDING_CLOSURE', 'COMPLETED', 'CANCELLED'));
CREATE INDEX ix_care_requests_provider ON care_requests (assigned_provider_id, status);

-- Providers switch this on/off in their portal (Phase 7).
ALTER TABLE providers ADD COLUMN is_available BOOLEAN NOT NULL DEFAULT TRUE;

-- Individual home visits for a care request.
CREATE TABLE visits (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_request_id  BIGINT        REFERENCES care_requests (id) ON DELETE SET NULL,
    provider_id      BIGINT        NOT NULL REFERENCES providers (id),
    patient_id       BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    service_type     VARCHAR(100),
    scheduled_at     TIMESTAMPTZ   NOT NULL,
    duration_minutes INTEGER,
    address          VARCHAR(300),
    location_area    VARCHAR(60),
    status           VARCHAR(20)   NOT NULL DEFAULT 'SCHEDULED',
    check_in_at      TIMESTAMPTZ,
    check_out_at     TIMESTAMPTZ,
    notes            TEXT,
    created_by_id    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_visits_status CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'MISSED'))
);
CREATE INDEX ix_visits_scheduled ON visits (scheduled_at);
CREATE INDEX ix_visits_provider  ON visits (provider_id, scheduled_at);
CREATE INDEX ix_visits_patient   ON visits (patient_id, scheduled_at);
CREATE INDEX ix_visits_request   ON visits (care_request_id);

ALTER TABLE visits ENABLE ROW LEVEL SECURITY;
