-- V14: DiGi's own lab scientists and pharmacists (/lab/me, /pharmacy/me).
--   service_requests: requests from the medical team, fulfilled at the patient's home.
--   catalogue_items:  DiGi's test / drug price list (drugs also carry stock).
--   stock_movements:  every stock change, for the audit trail.

CREATE TABLE service_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               VARCHAR(10)    NOT NULL,                 -- LAB | PHARMACY
    request_number     VARCHAR(30)    NOT NULL UNIQUE,
    status             VARCHAR(20)    NOT NULL DEFAULT 'NEW',   -- NEW | ACCEPTED | IN_PROGRESS | COMPLETED | DECLINED
    priority           VARCHAR(10)    NOT NULL DEFAULT 'ROUTINE', -- ROUTINE | URGENT | STAT
    due_date           DATE,
    scheduled_at       TIMESTAMPTZ,
    patient_id         BIGINT         REFERENCES patients (id) ON DELETE SET NULL,
    patient_name       VARCHAR(150)   NOT NULL,
    patient_phone      VARCHAR(30),
    address            VARCHAR(300),
    location_area      VARCHAR(60),
    patient_type       VARCHAR(20),
    requested_by_id    BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    requested_by_name  VARCHAR(150),
    requested_by_role  VARCHAR(40),
    notes              TEXT,
    lines              TEXT           NOT NULL,                 -- JSON [{ id, name, quantity, unitPrice, instructions, sampleType, catalogueItemId }]
    total_amount       NUMERIC(14,2),
    handled_by_id      BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    accepted_at        TIMESTAMPTZ,
    accept_note        TEXT,
    declined_at        TIMESTAMPTZ,
    decline_reason     TEXT,
    started_at         TIMESTAMPTZ,
    start_note         TEXT,
    completed_at       TIMESTAMPTZ,
    result_summary     TEXT,
    abnormal           BOOLEAN        NOT NULL DEFAULT FALSE,
    result_file_id     BIGINT         REFERENCES stored_files (id),
    received_by        VARCHAR(150),
    delivery_note      TEXT,
    proof_file_id      BIGINT         REFERENCES stored_files (id),
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_svc_req_kind CHECK (kind IN ('LAB', 'PHARMACY')),
    CONSTRAINT ck_svc_req_status CHECK (status IN ('NEW', 'ACCEPTED', 'IN_PROGRESS', 'COMPLETED', 'DECLINED'))
);
CREATE INDEX ix_svc_req_kind    ON service_requests (kind, status, created_at DESC);
CREATE INDEX ix_svc_req_handler ON service_requests (handled_by_id);
CREATE INDEX ix_svc_req_patient ON service_requests (patient_id);

CREATE TABLE catalogue_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              VARCHAR(10)    NOT NULL,                  -- LAB | PHARMACY
    name              VARCHAR(150)   NOT NULL,
    code              VARCHAR(30),
    unit_price        NUMERIC(12,2)  NOT NULL CHECK (unit_price > 0),
    strength          VARCHAR(60),                              -- drugs
    form              VARCHAR(60),                              -- drugs: tablet, syrup...
    sample_type       VARCHAR(30),                              -- tests
    turnaround_hours  INTEGER,                                  -- tests
    stock             INTEGER        CHECK (stock >= 0),        -- drugs only
    reorder_level     INTEGER        NOT NULL DEFAULT 10,
    active            BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_catalogue_kind CHECK (kind IN ('LAB', 'PHARMACY'))
);
CREATE UNIQUE INDEX ux_catalogue_name ON catalogue_items (kind, lower(name), lower(coalesce(strength, '')));

CREATE TABLE stock_movements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        BIGINT        NOT NULL REFERENCES catalogue_items (id) ON DELETE CASCADE,
    change         INTEGER       NOT NULL,
    balance_after  INTEGER       NOT NULL,
    reason         VARCHAR(300)  NOT NULL,
    request_id     BIGINT        REFERENCES service_requests (id) ON DELETE SET NULL,
    by_id          BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_stock_item ON stock_movements (item_id, created_at DESC);

ALTER TABLE service_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalogue_items  ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_movements  ENABLE ROW LEVEL SECURITY;
