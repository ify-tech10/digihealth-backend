-- V15: HMO organisation portal (/hmo/me).
--   hmo_employees:            a company's staff on its plan; each is also a PATIENT user with patient_type HMO.
--   hmo_uploads:              bulk CSV uploads and what happened to each row.
--   hmo_plan_change_requests: the company asking DiGi to move it to another plan.

CREATE TABLE hmo_uploads (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id    BIGINT        NOT NULL REFERENCES hmo_organisations (id),
    file_name          VARCHAR(200)  NOT NULL,
    total_rows         INTEGER       NOT NULL DEFAULT 0,
    created            INTEGER       NOT NULL DEFAULT 0,
    updated            INTEGER       NOT NULL DEFAULT 0,
    skipped            INTEGER       NOT NULL DEFAULT 0,
    errors             TEXT,                                  -- JSON [{ row, message }]
    status             VARCHAR(20)   NOT NULL DEFAULT 'COMPLETED',  -- COMPLETED | PARTIAL | FAILED
    uploaded_by_id     BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    uploaded_by_name   VARCHAR(150),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_hmo_uploads_org ON hmo_uploads (organisation_id, created_at DESC);

CREATE TABLE hmo_employees (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id     BIGINT        NOT NULL REFERENCES hmo_organisations (id),
    user_id             BIGINT        NOT NULL REFERENCES users (id),
    first_name          VARCHAR(80)   NOT NULL,
    last_name           VARCHAR(80)   NOT NULL,
    department          VARCHAR(100),
    staff_id            VARCHAR(50),
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    deactivated_at      TIMESTAMPTZ,
    deactivated_reason  TEXT,
    invited_at          TIMESTAMPTZ,
    upload_id           BIGINT        REFERENCES hmo_uploads (id) ON DELETE SET NULL,
    created_by_id       BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_hmo_employee UNIQUE (organisation_id, user_id)
);
CREATE INDEX ix_hmo_employees_user ON hmo_employees (user_id);

CREATE TABLE hmo_plan_change_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id    BIGINT        NOT NULL REFERENCES hmo_organisations (id),
    current_plan_id    BIGINT        REFERENCES hmo_plans (id),
    requested_plan_id  BIGINT        NOT NULL REFERENCES hmo_plans (id),
    note               TEXT,
    status             VARCHAR(20)   NOT NULL DEFAULT 'PENDING',  -- PENDING | DONE | DECLINED
    requested_by_id    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_hmo_plan_change_org ON hmo_plan_change_requests (organisation_id, status);

ALTER TABLE hmo_uploads              ENABLE ROW LEVEL SECURITY;
ALTER TABLE hmo_employees            ENABLE ROW LEVEL SECURITY;
ALTER TABLE hmo_plan_change_requests ENABLE ROW LEVEL SECURITY;
