-- V8: HMO plans and subscriptions, payments, staff financial requests and
-- invoices that facilities send to DiGi Health. Money is in naira.

CREATE TABLE hmo_plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(120)   NOT NULL,
    annual_price      NUMERIC(14,2)  NOT NULL CHECK (annual_price > 0),
    benefit_limit     NUMERIC(14,2)  NOT NULL CHECK (benefit_limit > 0),
    duration_months   INTEGER        NOT NULL DEFAULT 12 CHECK (duration_months > 0),
    description       TEXT,
    covered_services  TEXT           NOT NULL,          -- comma-separated codes, e.g. ELDERLY_CARE,TELEMEDICINE
    active            BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_hmo_plans_name ON hmo_plans (lower(name));

-- A company (ORGANISATION) or a single patient (INDIVIDUAL) on a plan for a year.
CREATE TABLE hmo_subscriptions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id            BIGINT         NOT NULL REFERENCES hmo_plans (id),
    subscriber_type    VARCHAR(12)    NOT NULL,
    organisation_id    BIGINT         REFERENCES hmo_organisations (id),
    patient_id         BIGINT         REFERENCES users (id),
    member_count       INTEGER        NOT NULL DEFAULT 1 CHECK (member_count >= 1),
    start_date         DATE           NOT NULL,
    expiry_date        DATE           NOT NULL,
    status             VARCHAR(20)    NOT NULL,         -- PENDING_PAYMENT | ACTIVE | CANCELLED (expired is worked out from the date)
    payment_reference  VARCHAR(100),
    amount_paid        NUMERIC(14,2),
    benefit_used       NUMERIC(14,2)  NOT NULL DEFAULT 0,
    created_by_id      BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_hmo_sub_type   CHECK (subscriber_type IN ('ORGANISATION', 'INDIVIDUAL')),
    CONSTRAINT ck_hmo_sub_status CHECK (status IN ('PENDING_PAYMENT', 'ACTIVE', 'CANCELLED')),
    CONSTRAINT ck_hmo_sub_owner  CHECK ((subscriber_type = 'ORGANISATION' AND organisation_id IS NOT NULL)
                                     OR (subscriber_type = 'INDIVIDUAL' AND patient_id IS NOT NULL)),
    CONSTRAINT ck_hmo_sub_dates  CHECK (expiry_date >= start_date)
);
CREATE INDEX ix_hmo_sub_org     ON hmo_subscriptions (organisation_id);
CREATE INDEX ix_hmo_sub_patient ON hmo_subscriptions (patient_id);
CREATE INDEX ix_hmo_sub_expiry  ON hmo_subscriptions (expiry_date);

-- Money received (patients, companies). Paystack payments arrive in Phase 12.
CREATE TABLE payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_name           VARCHAR(200)   NOT NULL,
    payer_user_id        BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    hmo_subscription_id  BIGINT         REFERENCES hmo_subscriptions (id) ON DELETE SET NULL,
    invoice_id           BIGINT,                       -- patient invoices (Phase 12)
    amount               NUMERIC(14,2)  NOT NULL CHECK (amount > 0),
    method               VARCHAR(30),                  -- BANK_TRANSFER | CARD | PAYSTACK | CASH | MANUAL
    reference            VARCHAR(100)   NOT NULL,
    description          VARCHAR(300),
    status               VARCHAR(20)    NOT NULL DEFAULT 'PAID',   -- PAID | PENDING | FAILED | REFUNDED
    paid_at              TIMESTAMPTZ,
    recorded_by_id       BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payments_created ON payments (created_at DESC);
CREATE INDEX ix_payments_payer   ON payments (payer_user_id);

-- Money requests raised by the CNO / medical director / finance manager; Admin approves.
CREATE TABLE financial_requests (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(200)   NOT NULL,
    category            VARCHAR(60)    NOT NULL,
    amount              NUMERIC(14,2)  NOT NULL CHECK (amount > 0),
    needed_by           DATE,
    description         TEXT,
    attachment_file_id  BIGINT         REFERENCES stored_files (id),
    requested_by_id     BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    requested_by_name   VARCHAR(150),
    requested_by_role   VARCHAR(40),
    status              VARCHAR(20)    NOT NULL DEFAULT 'PENDING',  -- PENDING | APPROVED | REJECTED | PAID
    review_note         TEXT,
    reviewed_by_id      BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_fin_req_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'PAID'))
);
CREATE INDEX ix_fin_req_status ON financial_requests (status, created_at DESC);
CREATE INDEX ix_fin_req_by     ON financial_requests (requested_by_id);

-- Bills from hospitals / pharmacies / labs to DiGi: Admin approves, Finance pays.
CREATE TABLE facility_invoices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id         BIGINT         NOT NULL REFERENCES facilities (id),
    invoice_number      VARCHAR(30)    NOT NULL UNIQUE,
    request_id          BIGINT,                        -- the referral / order / test request (Phase 11)
    patient_name        VARCHAR(150),
    total_amount        NUMERIC(14,2)  NOT NULL CHECK (total_amount > 0),
    notes               TEXT,
    attachment_file_id  BIGINT         REFERENCES stored_files (id),
    status              VARCHAR(20)    NOT NULL DEFAULT 'PENDING',  -- PENDING | APPROVED | REJECTED | PAID
    review_note         TEXT,
    reviewed_by_id      BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at         TIMESTAMPTZ,
    paid_at             TIMESTAMPTZ,
    payment_reference   VARCHAR(100),
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_fac_inv_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'PAID'))
);
CREATE INDEX ix_fac_inv_status   ON facility_invoices (status, created_at DESC);
CREATE INDEX ix_fac_inv_facility ON facility_invoices (facility_id);

CREATE TABLE facility_invoice_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT         NOT NULL REFERENCES facility_invoices (id) ON DELETE CASCADE,
    description  VARCHAR(300)   NOT NULL,
    quantity     INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC(14,2)  NOT NULL CHECK (unit_price >= 0),
    amount       NUMERIC(14,2)  NOT NULL,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_fac_inv_items ON facility_invoice_items (invoice_id);

ALTER TABLE hmo_plans              ENABLE ROW LEVEL SECURITY;
ALTER TABLE hmo_subscriptions      ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments               ENABLE ROW LEVEL SECURITY;
ALTER TABLE financial_requests     ENABLE ROW LEVEL SECURITY;
ALTER TABLE facility_invoices      ENABLE ROW LEVEL SECURITY;
ALTER TABLE facility_invoice_items ENABLE ROW LEVEL SECURITY;
