-- V13: partner facility portals (hospital / pharmacy / lab admins).
--   facility_requests: referrals (hospital), drug orders (pharmacy), test requests (lab) sent by DiGi's care team.
--   lab_tests:         the test menu and prices each lab centre offers.

CREATE TABLE facility_requests (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id          BIGINT        NOT NULL REFERENCES facilities (id),
    kind                 VARCHAR(12)   NOT NULL,                 -- HOSPITAL | PHARMACY | LABORATORY
    reference            VARCHAR(30)   NOT NULL UNIQUE,
    status               VARCHAR(20)   NOT NULL DEFAULT 'NEW',
    urgency              VARCHAR(20)   NOT NULL DEFAULT 'ROUTINE', -- ROUTINE | URGENT | EMERGENCY
    patient_id           BIGINT        REFERENCES patients (id) ON DELETE SET NULL,
    patient_name         VARCHAR(150)  NOT NULL,
    patient_info         TEXT,                                   -- JSON { name, age, gender, phone, address, nextOfKin }
    reason               TEXT,
    diagnosis            TEXT,
    prior_care_summary   TEXT,
    vitals               TEXT,                                   -- JSON
    medications          TEXT,                                   -- JSON array
    allergies            TEXT,                                   -- JSON array
    clinical_notes       TEXT,
    lines                TEXT,                                   -- JSON: pharmacy items / lab tests (with results)
    attachment_file_id   BIGINT        REFERENCES stored_files (id),
    requested_by_id      BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    requested_by_name    VARCHAR(150),
    -- accept / decline
    accepted_at          TIMESTAMPTZ,
    accept_note          TEXT,
    declined_at          TIMESTAMPTZ,
    decline_reason       TEXT,
    -- hospital
    expected_arrival     TIMESTAMPTZ,
    ward                 VARCHAR(100),
    admitted_at          TIMESTAMPTZ,
    discharged_at        TIMESTAMPTZ,
    discharge_summary    TEXT,
    discharge_outcome    VARCHAR(30),
    follow_up            TEXT,
    discharge_file_id    BIGINT        REFERENCES stored_files (id),
    -- pharmacy
    dispatch_at          TIMESTAMPTZ,
    rider                VARCHAR(150),
    dispatched_at        TIMESTAMPTZ,
    delivered_at         TIMESTAMPTZ,
    received_by          VARCHAR(150),
    delivery_note        TEXT,
    proof_file_id        BIGINT        REFERENCES stored_files (id),
    -- lab
    collection_type      VARCHAR(10),                            -- HOME | WALK_IN
    scheduled_at         TIMESTAMPTZ,
    turnaround_hours     INTEGER,
    collected_at         TIMESTAMPTZ,
    collected_by         VARCHAR(150),
    sample_id            VARCHAR(60),
    patient_fasted       BOOLEAN,
    collection_note      TEXT,
    resulted_at          TIMESTAMPTZ,
    critical             BOOLEAN       NOT NULL DEFAULT FALSE,
    result_comment       TEXT,
    report_file_id       BIGINT        REFERENCES stored_files (id),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_fac_req_kind CHECK (kind IN ('HOSPITAL', 'PHARMACY', 'LABORATORY')),
    CONSTRAINT ck_fac_req_status CHECK (status IN ('NEW', 'ACCEPTED', 'DECLINED', 'ADMITTED', 'DISCHARGED',
                                                   'DISPATCHED', 'DELIVERED', 'COLLECTED', 'RESULTED'))
);
CREATE INDEX ix_fac_req_facility ON facility_requests (facility_id, status, created_at DESC);
CREATE INDEX ix_fac_req_patient  ON facility_requests (patient_id);

CREATE TABLE lab_tests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id       BIGINT         NOT NULL REFERENCES facilities (id),
    name              VARCHAR(150)   NOT NULL,
    code              VARCHAR(30),
    category          VARCHAR(40),
    sample_type       VARCHAR(30),
    price             NUMERIC(12,2)  NOT NULL CHECK (price > 0),
    turnaround_hours  INTEGER        NOT NULL CHECK (turnaround_hours > 0),
    fasting           BOOLEAN        NOT NULL DEFAULT FALSE,
    home_collection   BOOLEAN        NOT NULL DEFAULT TRUE,
    active            BOOLEAN        NOT NULL DEFAULT TRUE,
    preparation       TEXT,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_lab_tests_name ON lab_tests (facility_id, lower(name));

-- Facility payout account numbers are stored encrypted (AES-GCM, base64), which is longer than 20 chars.
ALTER TABLE facilities ALTER COLUMN account_number TYPE VARCHAR(255);

ALTER TABLE facility_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE lab_tests         ENABLE ROW LEVEL SECURITY;
