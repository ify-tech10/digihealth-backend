ALTER TABLE providers ALTER COLUMN address             DROP NOT NULL;
ALTER TABLE providers ALTER COLUMN years_of_experience DROP NOT NULL;
ALTER TABLE providers ALTER COLUMN availability_type   DROP NOT NULL;

-- One row per PATIENT user: type (standard / HMO) and the profile the
-- patient fills in under My Profile.
CREATE TABLE patients (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT        NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    patient_type              VARCHAR(10)   NOT NULL DEFAULT 'STANDARD',
    hmo_organisation_id       BIGINT        REFERENCES hmo_organisations (id) ON DELETE SET NULL,
    date_of_birth             DATE,
    gender                    VARCHAR(10),
    address                   VARCHAR(300),
    area_lga                  VARCHAR(100),
    landmark                  VARCHAR(200),
    next_of_kin_name          VARCHAR(150),
    next_of_kin_relationship  VARCHAR(60),
    next_of_kin_phone         VARCHAR(30),
    blood_group               VARCHAR(5),
    genotype                  VARCHAR(5),
    allergies                 TEXT,
    conditions                TEXT,
    current_medications       TEXT,
    primary_doctor            VARCHAR(150),
    notify_sms                BOOLEAN       NOT NULL DEFAULT TRUE,
    notify_whatsapp           BOOLEAN       NOT NULL DEFAULT TRUE,
    notify_email              BOOLEAN       NOT NULL DEFAULT TRUE,
    consent_signed_at         TIMESTAMPTZ,
    created_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_patients_type CHECK (patient_type IN ('STANDARD', 'HMO'))
);
CREATE INDEX ix_patients_hmo ON patients (hmo_organisation_id);

-- Patients who signed up before this table existed.
INSERT INTO patients (user_id, address)
SELECT u.id,
       (SELECT cr.address FROM care_requests cr
         WHERE cr.patient_id = u.id AND cr.address IS NOT NULL
         ORDER BY cr.created_at DESC LIMIT 1)
FROM users u
WHERE u.role = 'PATIENT'
  AND NOT EXISTS (SELECT 1 FROM patients p WHERE p.user_id = u.id);

ALTER TABLE patients ENABLE ROW LEVEL SECURITY;
