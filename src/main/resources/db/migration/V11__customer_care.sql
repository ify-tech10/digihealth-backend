-- V11: Customer Care desk.

-- Tickets can also be logged by an agent for a caller who isn't a registered patient.
ALTER TABLE support_tickets ALTER COLUMN patient_id DROP NOT NULL;
ALTER TABLE support_tickets
    ADD COLUMN caller_name           VARCHAR(150),
    ADD COLUMN caller_phone          VARCHAR(30),
    ADD COLUMN caller_email          VARCHAR(255),
    ADD COLUMN channel               VARCHAR(12)  NOT NULL DEFAULT 'PORTAL',  -- PORTAL | PHONE | WHATSAPP | EMAIL | WALK_IN
    ADD COLUMN created_by_agent_id   BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN first_response_at     TIMESTAMPTZ,
    ADD COLUMN first_response_by_id  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN escalated_to          VARCHAR(30),                              -- CNO | FINANCE | RELATIONSHIP_MANAGER | ADMIN
    ADD COLUMN escalation_note       TEXT,
    ADD COLUMN escalated_at          TIMESTAMPTZ,
    ADD COLUMN escalated_by_id       BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN resolution_note       TEXT,
    ADD COLUMN resolved_by_id        BIGINT       REFERENCES users (id) ON DELETE SET NULL;

ALTER TABLE support_tickets ADD CONSTRAINT ck_ticket_owner CHECK (patient_id IS NOT NULL OR caller_name IS NOT NULL);

-- PENDING = an agent replied and is waiting for the patient.
ALTER TABLE support_tickets DROP CONSTRAINT ck_ticket_status;
ALTER TABLE support_tickets ADD CONSTRAINT ck_ticket_status
    CHECK (status IN ('OPEN', 'PENDING', 'IN_PROGRESS', 'ESCALATED', 'RESOLVED', 'CLOSED'));

CREATE INDEX ix_ticket_messages_sender ON ticket_messages (sender_id, created_at);

-- Online / Away for each agent.
CREATE TABLE agent_status (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    status      VARCHAR(10)  NOT NULL DEFAULT 'ONLINE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_agent_status CHECK (status IN ('ONLINE', 'AWAY'))
);

ALTER TABLE agent_status ENABLE ROW LEVEL SECURITY;
