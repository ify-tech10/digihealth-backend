-- V16: Finance Manager portal and online payments (Paystack).

-- Bills from DiGi to patients and companies.
CREATE TABLE invoices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number      VARCHAR(30)    NOT NULL UNIQUE,
    client_type         VARCHAR(20)    NOT NULL,                 -- PATIENT | ORGANISATION
    client_name         VARCHAR(200)   NOT NULL,
    client_email        VARCHAR(255),
    patient_user_id     BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    organisation_id     BIGINT         REFERENCES hmo_organisations (id) ON DELETE SET NULL,
    care_request_id     BIGINT         REFERENCES care_requests (id) ON DELETE SET NULL,
    service             VARCHAR(300)   NOT NULL,
    category            VARCHAR(40)    NOT NULL,
    amount              NUMERIC(14,2)  NOT NULL CHECK (amount > 0),
    vat_percent         NUMERIC(5,2)   NOT NULL DEFAULT 0,
    vat_amount          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    total_amount        NUMERIC(14,2)  NOT NULL CHECK (total_amount > 0),
    amount_paid         NUMERIC(14,2)  NOT NULL DEFAULT 0,
    status              VARCHAR(20)    NOT NULL DEFAULT 'PENDING',  -- PENDING | PARTIAL | PAID | CANCELLED
    due_date            DATE           NOT NULL,
    notes               TEXT,
    cancel_reason       TEXT,
    cancelled_at        TIMESTAMPTZ,
    paid_at             TIMESTAMPTZ,
    reminder_count      INTEGER        NOT NULL DEFAULT 0,
    last_reminded_at    TIMESTAMPTZ,
    created_by_id       BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_invoices_client CHECK (client_type IN ('PATIENT', 'ORGANISATION')),
    CONSTRAINT ck_invoices_status CHECK (status IN ('PENDING', 'PARTIAL', 'PAID', 'CANCELLED'))
);
CREATE INDEX ix_invoices_status  ON invoices (status, due_date);
CREATE INDEX ix_invoices_patient ON invoices (patient_user_id);

-- Payments: link to invoices, and online (Paystack) attempts that start PENDING.
ALTER TABLE payments ADD CONSTRAINT fk_payments_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE SET NULL;
CREATE UNIQUE INDEX ux_payments_paystack_ref ON payments (reference) WHERE method = 'PAYSTACK';
CREATE INDEX ix_payments_invoice ON payments (invoice_id);
CREATE INDEX ix_payments_paid_at ON payments (paid_at);

-- Claims DiGi sends to insurers for HMO care.
CREATE TABLE hmo_claims (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number         VARCHAR(30)    NOT NULL UNIQUE,
    organisation_name    VARCHAR(200)   NOT NULL,
    organisation_id      BIGINT         REFERENCES hmo_organisations (id) ON DELETE SET NULL,
    hmo_provider         VARCHAR(200)   NOT NULL,
    service_period       VARCHAR(7)     NOT NULL,                 -- YYYY-MM
    members              INTEGER,
    amount_claimed       NUMERIC(14,2)  NOT NULL CHECK (amount_claimed > 0),
    amount_received      NUMERIC(14,2),
    status               VARCHAR(20)    NOT NULL DEFAULT 'PENDING',  -- PENDING | QUERIED | PAID | REJECTED
    submitted_at         DATE           NOT NULL,
    notes                TEXT,
    follow_up_count      INTEGER        NOT NULL DEFAULT 0,
    last_follow_up_at    TIMESTAMPTZ,
    last_follow_up_note  TEXT,
    paid_at              DATE,
    payment_reference    VARCHAR(100),
    created_by_id        BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_hmo_claims_status CHECK (status IN ('PENDING', 'QUERIED', 'PAID', 'REJECTED'))
);
CREATE INDEX ix_hmo_claims_status ON hmo_claims (status, submitted_at DESC);

-- Expense claims = financial requests Admin approved; Finance then releases the money or refuses.
ALTER TABLE financial_requests
    ADD COLUMN finance_decision        VARCHAR(20),          -- null (waiting) | APPROVED | REJECTED
    ADD COLUMN finance_note            TEXT,
    ADD COLUMN finance_reviewed_by_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN finance_reviewed_at     TIMESTAMPTZ;

-- Facility bills: how Finance paid.
ALTER TABLE facility_invoices ADD COLUMN payment_method VARCHAR(30);

-- Salaried office staff (providers are paid by their earning structure instead).
CREATE TABLE staff_salaries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT         NOT NULL UNIQUE REFERENCES users (id),
    monthly_salary      NUMERIC(14,2)  NOT NULL CHECK (monthly_salary > 0),
    allowances          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    deductions          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    bank_name           VARCHAR(100),
    account_name        VARCHAR(150),
    account_number_enc  TEXT,                                    -- AES-GCM, like providers
    active              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- One line per person per processed month.
CREATE TABLE payroll_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month               VARCHAR(7)     NOT NULL,                 -- YYYY-MM
    user_id             BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    provider_id         BIGINT         REFERENCES providers (id) ON DELETE SET NULL,
    payout_id           BIGINT         REFERENCES provider_payouts (id) ON DELETE SET NULL,
    staff_name          VARCHAR(150)   NOT NULL,
    role                VARCHAR(40),
    pay_basis           VARCHAR(20)    NOT NULL,                 -- SALARY | PER_REQUEST | WEEKLY | MONTHLY
    requests_completed  INTEGER,
    gross_pay           NUMERIC(14,2)  NOT NULL,
    allowances          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    deductions          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    net_pay             NUMERIC(14,2)  NOT NULL,
    bank_name           VARCHAR(100),
    account_name        VARCHAR(150),
    account_number_enc  TEXT,
    status              VARCHAR(20)    NOT NULL DEFAULT 'PENDING',  -- PENDING | PAID
    reference           VARCHAR(100),
    paid_at             TIMESTAMPTZ,
    processed_by_id     BIGINT         REFERENCES users (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payroll_month ON payroll_lines (month);

-- Monthly budget per category.
CREATE TABLE budget_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month       VARCHAR(7)     NOT NULL,
    category    VARCHAR(100)   NOT NULL,
    budgeted    NUMERIC(14,2)  NOT NULL CHECK (budgeted >= 0),
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_budget_month_cat ON budget_lines (month, lower(category));

ALTER TABLE invoices       ENABLE ROW LEVEL SECURITY;
ALTER TABLE hmo_claims     ENABLE ROW LEVEL SECURITY;
ALTER TABLE staff_salaries ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_lines  ENABLE ROW LEVEL SECURITY;
ALTER TABLE budget_lines   ENABLE ROW LEVEL SECURITY;
