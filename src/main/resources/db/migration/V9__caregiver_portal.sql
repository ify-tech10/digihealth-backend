-- V9: everything the caregiver portal stores.

-- Coverage areas, working hours, bank details and earning setup on the provider.
ALTER TABLE providers
    ADD COLUMN coverage_areas      TEXT,                -- comma-separated area codes chosen on My Availability
    ADD COLUMN default_start_time  TIME,
    ADD COLUMN default_end_time    TIME,
    ADD COLUMN bank_name           VARCHAR(100),
    ADD COLUMN account_name        VARCHAR(150),
    ADD COLUMN account_number_enc  TEXT,                -- AES-GCM encrypted; never stored in plain text
    ADD COLUMN account_last4       VARCHAR(4),
    ADD COLUMN bvn_enc             TEXT,
    ADD COLUMN bvn_last4           VARCHAR(4),
    ADD COLUMN nin_enc             TEXT,
    ADD COLUMN nin_last4           VARCHAR(4),
    ADD COLUMN earning_structure   VARCHAR(20),         -- PER_REQUEST | WEEKLY | MONTHLY
    ADD COLUMN earning_rate        NUMERIC(14,2),
    ADD COLUMN earning_status      VARCHAR(20),         -- PENDING | APPROVED | REJECTED
    ADD COLUMN earning_updated_at  TIMESTAMPTZ;

ALTER TABLE visits ADD COLUMN title VARCHAR(150);

-- Day-by-day availability.
CREATE TABLE provider_availability (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id  BIGINT       NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    day          DATE         NOT NULL,
    available    BOOLEAN      NOT NULL,
    start_time   TIME,
    end_time     TIME,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_provider_day UNIQUE (provider_id, day)
);

-- What the provider recorded at a visit. The CNO reviews it (Phase 9);
-- approved reports become visible to the patient.
CREATE TABLE visit_reports (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_request_id    BIGINT        NOT NULL REFERENCES care_requests (id),
    visit_id           BIGINT        UNIQUE REFERENCES visits (id) ON DELETE SET NULL,
    provider_id        BIGINT        NOT NULL REFERENCES providers (id),
    patient_id         BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    visit_date         DATE          NOT NULL,
    activities         TEXT          NOT NULL,          -- comma-separated codes
    patient_condition  VARCHAR(20)   NOT NULL,          -- IMPROVING | STABLE | DETERIORATING
    medication_given   TEXT,
    notes              TEXT          NOT NULL,
    next_steps         TEXT,
    blood_pressure     VARCHAR(10),
    pulse              INTEGER,
    temperature        NUMERIC(4,1),
    spo2               INTEGER,
    blood_sugar        NUMERIC(5,1),
    respiratory_rate   INTEGER,
    status             VARCHAR(20)   NOT NULL DEFAULT 'SUBMITTED',  -- SUBMITTED | APPROVED | RETURNED
    review_note        TEXT,
    reviewed_by_id     BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_report_condition CHECK (patient_condition IN ('IMPROVING', 'STABLE', 'DETERIORATING')),
    CONSTRAINT ck_report_status    CHECK (status IN ('SUBMITTED', 'APPROVED', 'RETURNED'))
);
CREATE INDEX ix_reports_provider ON visit_reports (provider_id, visit_date DESC);
CREATE INDEX ix_reports_request  ON visit_reports (care_request_id);
CREATE INDEX ix_reports_status   ON visit_reports (status, created_at DESC);

-- Payouts to providers, written by Finance (Phase 12).
CREATE TABLE provider_payouts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id      BIGINT         NOT NULL REFERENCES providers (id),
    period_start     DATE           NOT NULL,
    period_end       DATE           NOT NULL,
    completed_visits INTEGER        NOT NULL DEFAULT 0,
    structure        VARCHAR(20),
    amount           NUMERIC(14,2)  NOT NULL,
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING',     -- PENDING | PAID
    reference        VARCHAR(100),
    paid_at          TIMESTAMPTZ,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payouts_provider ON provider_payouts (provider_id, period_end DESC);

ALTER TABLE provider_availability ENABLE ROW LEVEL SECURITY;
ALTER TABLE visit_reports         ENABLE ROW LEVEL SECURITY;
ALTER TABLE provider_payouts      ENABLE ROW LEVEL SECURITY;
