-- V7: partner facilities (hospitals, pharmacies, laboratories).
-- Each has one admin login (HOSPITAL_ADMIN / PHARMACY_ADMIN / LAB_ADMIN).
-- The profile columns are filled in by the facility in its own portal (Phase 11).

CREATE TABLE facilities (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                 VARCHAR(12)   NOT NULL,           -- HOSPITAL | PHARMACY | LABORATORY
    name                 VARCHAR(200)  NOT NULL,
    email                VARCHAR(255)  NOT NULL,           -- the facility admin's login email
    phone_number         VARCHAR(30)   NOT NULL,
    address              VARCHAR(300)  NOT NULL,
    location_area        VARCHAR(60)   NOT NULL,
    contact_person       VARCHAR(150)  NOT NULL,
    active               BOOLEAN       NOT NULL DEFAULT TRUE,
    admin_user_id        BIGINT        UNIQUE REFERENCES users (id) ON DELETE SET NULL,
    -- profile (facility portal)
    opening_hours        VARCHAR(200),
    accepting            BOOLEAN       NOT NULL DEFAULT TRUE,   -- accepting new referrals / orders
    beds_available       INTEGER,                               -- hospitals
    delivery_areas       TEXT,                                  -- pharmacies, comma-separated
    home_collection      BOOLEAN       NOT NULL DEFAULT FALSE,  -- labs
    collection_areas     TEXT,                                  -- labs, comma-separated
    registration_number  VARCHAR(80),                           -- e.g. MLSCN / PCN / MDCN number
    bank_name            VARCHAR(100),
    account_name         VARCHAR(150),
    account_number       VARCHAR(20),
    created_by_id        BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    deleted_at           TIMESTAMPTZ,                           -- removed from Admin lists, kept for history
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_facilities_kind CHECK (kind IN ('HOSPITAL', 'PHARMACY', 'LABORATORY'))
);
CREATE INDEX ix_facilities_kind ON facilities (kind, deleted_at);
CREATE INDEX ix_facilities_area ON facilities (location_area);

ALTER TABLE facilities ENABLE ROW LEVEL SECURITY;
